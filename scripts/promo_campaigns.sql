CREATE TABLE IF NOT EXISTS public.promo_campaign_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_slug text NOT NULL REFERENCES public.promo_campaigns (slug) ON DELETE RESTRICT,
  user_id text NOT NULL,
  prize_tier text NOT NULL,
  recipient_name text NOT NULL,
  phone text NOT NULL,
  address text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT promo_campaign_claims_user_per_campaign UNIQUE (campaign_slug, user_id)
);

CREATE INDEX IF NOT EXISTS idx_promo_campaign_claims_slug ON public.promo_campaign_claims (campaign_slug);
CREATE INDEX IF NOT EXISTS idx_promo_campaign_claims_created ON public.promo_campaign_claims (created_at);

-- -----------------------------------------------------------------------------
-- 多档位奖项（任意数量；sort_order 越小越优先，与先到先得一致）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.promo_campaign_prize_tiers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_slug text NOT NULL REFERENCES public.promo_campaigns (slug) ON DELETE CASCADE,
  tier_key text NOT NULL,
  tier_name text NOT NULL DEFAULT '',
  sort_order int NOT NULL,
  slots int NOT NULL DEFAULT 0 CHECK (slots >= 0),
  label text NOT NULL DEFAULT '',
  CONSTRAINT promo_campaign_prize_tiers_slug_key UNIQUE (campaign_slug, tier_key),
  CONSTRAINT promo_campaign_prize_tiers_slug_sort UNIQUE (campaign_slug, sort_order),
  CONSTRAINT promo_campaign_prize_tiers_key_fmt CHECK (
    tier_key ~ '^[a-z][a-z0-9_]*$' AND char_length(tier_key) <= 32
  )
);

CREATE INDEX IF NOT EXISTS idx_promo_campaign_prize_tiers_slug ON public.promo_campaign_prize_tiers (campaign_slug);

COMMENT ON TABLE public.promo_campaign_prize_tiers IS '活动奖项档位；claim.prize_tier 存 tier_key';


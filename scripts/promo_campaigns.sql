-- 按活动配置计算：仅统计 window_start_date～window_end_date（含端点）内、按活动 tz 换算的日历日；
-- 连续「有记录」的日历日以 created_at（入库时间）为准，避免手动补录把 recorded_at 填成任意测量日刷连续；
-- 无 created_at 的旧数据回退到 recorded_at。直接扫 bp_records，不受客户端分页影响。
CREATE OR REPLACE FUNCTION public.promo_campaign_max_streak(p_user_id text, p_slug text)
RETURNS integer
LANGUAGE plpgsql
STABLE
AS $func$
DECLARE
  ws date;
  we date;
  tzv text;
  d date;
  prev date;
  cur int := 0;
  best int := 0;
BEGIN
  SELECT c.window_start_date, c.window_end_date, c.tz
  INTO ws, we, tzv
  FROM public.promo_campaigns c
  WHERE c.slug = p_slug AND c.is_enabled;

  IF ws IS NULL THEN
    RETURN 0;
  END IF;

  FOR d IN
    SELECT DISTINCT (timezone(tzv::text, COALESCE(r.created_at, r.recorded_at)))::date AS day
    FROM public.bp_records r
    WHERE r.user_id = p_user_id
      AND (timezone(tzv::text, COALESCE(r.created_at, r.recorded_at)))::date >= ws
      AND (timezone(tzv::text, COALESCE(r.created_at, r.recorded_at)))::date <= we
    ORDER BY 1
  LOOP
    IF prev IS NULL THEN
      cur := 1;
    ELSIF d = prev + 1 THEN
      cur := cur + 1;
    ELSE
      cur := 1;
    END IF;
    IF cur > best THEN
      best := cur;
    END IF;
    prev := d;
  END LOOP;
  RETURN best;
END;
$func$;

CREATE OR REPLACE FUNCTION public.promo_campaign_streak_status(p_user_id text, p_slug text)
RETURNS jsonb
LANGUAGE plpgsql
AS $func$
DECLARE
  camp public.promo_campaigns%ROWTYPE;
  v_today date;
  v_phase text;
  v_streak int;
  v_claim jsonb;
  v_grand_left int;
  v_second_left int;
  v_prize_tiers jsonb;
  v_grand_slots int;
  v_second_slots int;
  req int;
BEGIN
  SELECT * INTO camp FROM public.promo_campaigns WHERE slug = p_slug LIMIT 1;

  IF NOT FOUND OR NOT camp.is_enabled THEN
    RETURN jsonb_build_object(
      'ok', false,
      'error', 'campaign_not_found',
      'campaign_slug', p_slug
    );
  END IF;

  v_today := (timezone(camp.tz::text, now()))::date;

  IF v_today < camp.window_start_date THEN
    v_phase := 'not_started';
  ELSIF v_today > camp.window_end_date THEN
    v_phase := 'ended';
  ELSE
    v_phase := 'active';
  END IF;

  req := camp.required_streak_days;
  v_streak := public.promo_campaign_max_streak(p_user_id, p_slug);

  SELECT jsonb_build_object(
    'prize_tier', c.prize_tier,
    'tier_name', COALESCE(pt.tier_name, c.prize_tier),
    'recipient_name', c.recipient_name,
    'phone', c.phone,
    'address', c.address,
    'created_at', c.created_at
  )
  INTO v_claim
  FROM public.promo_campaign_claims c
  LEFT JOIN public.promo_campaign_prize_tiers pt
    ON pt.campaign_slug = c.campaign_slug AND pt.tier_key = c.prize_tier
  WHERE c.campaign_slug = p_slug AND c.user_id = p_user_id
  LIMIT 1;

  SELECT COALESCE(
    (
      SELECT jsonb_agg(
        jsonb_build_object(
          'tier_key', t.tier_key,
          'tier_name', t.tier_name,
          'sort_order', t.sort_order,
          'slots', t.slots,
          'label', t.label,
          'remaining', GREATEST(
            t.slots - COALESCE((
              SELECT COUNT(*)::int FROM public.promo_campaign_claims cc
              WHERE cc.campaign_slug = p_slug AND cc.prize_tier = t.tier_key
            ), 0),
            0
          )
        )
        ORDER BY t.sort_order
      )
      FROM public.promo_campaign_prize_tiers t
      WHERE t.campaign_slug = p_slug
    ),
    '[]'::jsonb
  ) INTO v_prize_tiers;

  v_grand_slots := COALESCE((
    SELECT slots FROM public.promo_campaign_prize_tiers
    WHERE campaign_slug = p_slug AND tier_key = 'grand' LIMIT 1
  ), camp.grand_prize_slots);
  v_second_slots := COALESCE((
    SELECT slots FROM public.promo_campaign_prize_tiers
    WHERE campaign_slug = p_slug AND tier_key = 'second' LIMIT 1
  ), camp.second_prize_slots);

  v_grand_left := v_grand_slots - COALESCE((
    SELECT COUNT(*)::int FROM public.promo_campaign_claims
    WHERE campaign_slug = p_slug AND prize_tier = 'grand'
  ), 0);
  v_second_left := v_second_slots - COALESCE((
    SELECT COUNT(*)::int FROM public.promo_campaign_claims
    WHERE campaign_slug = p_slug AND prize_tier = 'second'
  ), 0);

  RETURN jsonb_build_object(
    'ok', true,
    'campaign_slug', camp.slug,
    'title', camp.title,
    'activity_phase', v_phase,
    'window_start', camp.window_start_date::text,
    'window_end', camp.window_end_date::text,
    'timezone', camp.tz,
    'required_streak_days', req,
    'prize_tiers', v_prize_tiers,
    'grand_prize_slots', v_grand_slots,
    'second_prize_slots', v_second_slots,
    'grand_prize_label', camp.grand_prize_label,
    'second_prize_label', camp.second_prize_label,
    'streak_days_in_window', v_streak,
    'qualified', (v_streak >= req),
    'my_claim', v_claim,
    'remaining_grand', GREATEST(v_grand_left, 0),
    'remaining_second', GREATEST(v_second_left, 0),
    'sold_out', NOT EXISTS (
      SELECT 1 FROM public.promo_campaign_prize_tiers t
      WHERE t.campaign_slug = p_slug
        AND t.slots > COALESCE((
          SELECT COUNT(*)::int FROM public.promo_campaign_claims c
          WHERE c.campaign_slug = p_slug AND c.prize_tier = t.tier_key
        ), 0)
    )
  );
END;
$func$;

CREATE OR REPLACE FUNCTION public.promo_campaign_streak_claim(
  p_user_id text,
  p_slug text,
  p_recipient_name text,
  p_phone text,
  p_address text
)
RETURNS jsonb
LANGUAGE plpgsql
AS $func$
DECLARE
  camp public.promo_campaigns%ROWTYPE;
  v_today date;
  v_streak int;
  v_prize text;
  v_prize_label text;
  v_used bigint;
  r record;
  v_name text := trim(both from coalesce(p_recipient_name, ''));
  v_phone text := trim(both from regexp_replace(coalesce(p_phone, ''), '\s', '', 'g'));
  v_addr text := trim(both from coalesce(p_address, ''));
  req int;
  v_cap int;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext(p_slug), 928471522);

  SELECT * INTO camp FROM public.promo_campaigns WHERE slug = p_slug LIMIT 1;
  IF NOT FOUND OR NOT camp.is_enabled THEN
    RETURN jsonb_build_object('ok', false, 'error', 'campaign_not_found');
  END IF;

  v_today := (timezone(camp.tz::text, now()))::date;

  IF v_today < camp.window_start_date THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_started');
  END IF;
  IF v_today > camp.window_end_date THEN
    RETURN jsonb_build_object('ok', false, 'error', 'ended');
  END IF;

  IF char_length(v_name) < 2 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_name');
  END IF;
  IF char_length(v_phone) < 8 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_phone');
  END IF;
  IF char_length(v_addr) < 6 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'invalid_address');
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.promo_campaign_claims
    WHERE campaign_slug = p_slug AND user_id = p_user_id
  ) THEN
    RETURN jsonb_build_object('ok', false, 'error', 'already_claimed');
  END IF;

  req := camp.required_streak_days;
  v_streak := public.promo_campaign_max_streak(p_user_id, p_slug);
  IF v_streak < req THEN
    RETURN jsonb_build_object('ok', false, 'error', 'not_qualified');
  END IF;

  v_cap := COALESCE((
    SELECT SUM(slots)::int FROM public.promo_campaign_prize_tiers WHERE campaign_slug = p_slug
  ), 0);

  IF v_cap <= 0 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'sold_out');
  END IF;

  FOR r IN
    SELECT tier_key, slots, label
    FROM public.promo_campaign_prize_tiers
    WHERE campaign_slug = p_slug
    ORDER BY sort_order ASC
  LOOP
    SELECT COUNT(*) INTO v_used
    FROM public.promo_campaign_claims
    WHERE campaign_slug = p_slug AND prize_tier = r.tier_key;

    IF v_used < r.slots THEN
      v_prize := r.tier_key;
      v_prize_label := r.label;
      EXIT;
    END IF;
  END LOOP;

  IF v_prize IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'sold_out');
  END IF;

  INSERT INTO public.promo_campaign_claims (campaign_slug, user_id, prize_tier, recipient_name, phone, address)
  VALUES (p_slug, p_user_id, v_prize, v_name, v_phone, v_addr);

  RETURN jsonb_build_object(
    'ok', true,
    'prize_tier', v_prize,
    'prize_label', v_prize_label,
    'campaign_slug', p_slug,
    'slots_total', v_cap
  );
EXCEPTION
  WHEN unique_violation THEN
    RETURN jsonb_build_object('ok', false, 'error', 'already_claimed');
END;
$func$;


-- =============================================================================
-- 【活动数据库】只需在 Supabase SQL Editor 中执行本文件这一份即可（不要执行别的 promo_*.sql）
-- =============================================================================
-- 可配置「连续记录领礼品」类活动（多期复用）
-- 1) promo_campaigns：每期一条（slug 唯一），配置统计窗口、所需连续天数；legacy 列 grand/second 与后台列表兼容
-- 2) promo_campaign_prize_tiers：任意数量奖项档位（sort_order 越小越优先，先到先得）
-- 3) promo_campaign_claims：按 campaign_slug + user_id 唯一，prize_tier 存 tier_key
--
-- 若库里曾存在旧表 public.promo_202604_consecutive_claims，文末 DO 块会自动把数据迁到本方案（可忽略若不存在）。
-- Next.js：GET/POST /api/promo/campaign（可选 ?slug= 覆盖环境变量）、PROMO_CAMPAIGN_SLUG、PROMO_ADMIN_KEY

CREATE TABLE IF NOT EXISTS public.promo_campaigns (
  slug text PRIMARY KEY,
  title text NOT NULL DEFAULT '',
  window_start_date date NOT NULL,
  window_end_date date NOT NULL,
  required_streak_days integer NOT NULL DEFAULT 30 CHECK (required_streak_days >= 1),
  grand_prize_slots integer NOT NULL DEFAULT 1 CHECK (grand_prize_slots >= 0),
  second_prize_slots integer NOT NULL DEFAULT 3 CHECK (second_prize_slots >= 0),
  grand_prize_label text NOT NULL DEFAULT '上臂式电子血压计 1 台',
  second_prize_label text NOT NULL DEFAULT '体脂秤/臂带/健康小礼品（随机）1 份',
  tz text NOT NULL DEFAULT 'Asia/Shanghai',
  is_enabled boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT promo_campaigns_window_ok CHECK (window_end_date >= window_start_date)
);

